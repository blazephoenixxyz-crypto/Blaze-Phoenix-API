#!/usr/bin/env node
// Writes src/abis/staking.generated.ts: the compiler's ABI of BlazePhoenixStaking, from a
// checkout of the Blaze-Phoenix-Staking repository. Nothing in it is written by hand.
//
//   node scripts/gen-staking-abi.mjs <staking-checkout>           write the file
//   node scripts/gen-staking-abi.mjs <staking-checkout> --check   exit 1 if the file differs
//
// solc and @openzeppelin come from the checkout's own node_modules (its compile.js uses the
// same), so this repository gains no dependency; NODE_MODULES=<dir> points elsewhere. The source
// revision is the checkout's HEAD on a clean tree; outside a git checkout STAKING_REV names it.
// No revision, no file: an ABI whose source cannot be named is not written.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { keccak256, toBytes } from 'viem';

const [dir, flag] = process.argv.slice(2);
if (!dir) { console.error('usage: gen-staking-abi.mjs <staking-checkout> [--check]'); process.exit(2); }
const nm = process.env.NODE_MODULES || join(dir, 'node_modules');
// createRequire needs an absolute path; CI passes the checkout as the relative path `staking`.
const solc = createRequire(resolve(nm, 'noop.js'))('solc');

let rev = process.env.STAKING_REV;
if (!rev) {
  try {
    if (execFileSync('git', ['-C', dir, 'status', '--porcelain', '--', 'src'], { encoding: 'utf8' }).trim()) {
      console.error('staking src/ has uncommitted changes: no revision names it'); process.exit(1);
    }
    rev = execFileSync('git', ['-C', dir, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  } catch { /* not a git checkout */ }
}
if (!/^[0-9a-f]{40}$/.test(rev ?? '')) { console.error('no source revision (40 hex): set STAKING_REV'); process.exit(1); }

const read = (p) => readFileSync(p, 'utf8');
const sources = Object.fromEntries(['src/BlazePhoenixStaking.sol', 'src/BlazePhoenixMathLib.sol']
  .map((f) => [f, { content: read(join(dir, f)) }]));
const findImports = (p) => {
  try { return { contents: read(p.startsWith('@openzeppelin/') ? join(nm, p) : join(dir, p)) }; } catch { return { error: `not found: ${p}` }; }
};
const out = JSON.parse(solc.compile(JSON.stringify({
  language: 'Solidity', sources,
  settings: { optimizer: { enabled: true, runs: 200 }, viaIR: true,
    outputSelection: { 'src/BlazePhoenixStaking.sol': { BlazePhoenixStaking: ['abi'] } } },
}), { import: findImports }));
const errors = (out.errors ?? []).filter((e) => e.severity === 'error');
if (errors.length) { for (const e of errors) console.error(e.formattedMessage); process.exit(1); }

// One key order, no internalType: the file changes only when the interface does.
const param = (p) => ({ name: p.name, type: p.type, ...(p.indexed !== undefined ? { indexed: p.indexed } : {}),
  ...(p.components ? { components: p.components.map(param) } : {}) });
const item = (x) => ({ type: x.type, ...(x.name !== undefined ? { name: x.name } : {}),
  inputs: (x.inputs ?? []).map(param), ...(x.outputs ? { outputs: x.outputs.map(param) } : {}),
  ...(x.stateMutability ? { stateMutability: x.stateMutability } : {}),
  ...(x.anonymous !== undefined ? { anonymous: x.anonymous } : {}) });
const abi = out.contracts['src/BlazePhoenixStaking.sol'].BlazePhoenixStaking.abi.map(item);

const text = `// =============================================================================
//  GENERATED by scripts/gen-staking-abi.mjs from Blaze-Phoenix-Staking — do not edit.
//  Source revision: ${rev}
//  Compiler: solc ${solc.version()}
//  ${abi.length} items. STAKING_ABI_DIGEST = keccak256 of JSON.stringify(STAKING_ABI); the
//  test suite recomputes it, so a hand edit here is red.
// =============================================================================

export const STAKING_ABI_SOURCE_REVISION = '${rev}' as const;
export const STAKING_ABI_COMPILER = 'solc ${solc.version()}' as const;
export const STAKING_ABI_DIGEST = '${keccak256(toBytes(JSON.stringify(abi)))}' as const;

export const STAKING_ABI = ${JSON.stringify(abi, null, 2)} as const;
`;
const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'abis', 'staking.generated.ts');
if (flag === '--check') {
  let now = '';
  try { now = read(target); } catch { /* absent */ }
  if (now !== text) { console.error(`${target} differs from the ABI of ${rev}: regenerate`); process.exit(1); }
  console.log(`staking ABI matches ${rev} (${abi.length} items)`);
} else {
  writeFileSync(target, text);
  console.log(`wrote ${target}: ${abi.length} items from ${rev}`);
}
